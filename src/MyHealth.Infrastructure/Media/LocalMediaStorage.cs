using System.Text.RegularExpressions;
using Microsoft.Extensions.Configuration;
using MyHealth.Application.Abstractions.Media;

namespace MyHealth.Infrastructure.Media;

/// <summary>
/// Media storage on the local disk (<c>Media:LocalPath</c>, default a folder in the system temp directory), for
/// development and tests. Public files are served by the API at <c>/media/{key}</c>; their URLs start with
/// <c>Media:PublicBaseUrl</c> (default the production media host). Production swaps this for a bucket behind the CDN.
/// </summary>
internal sealed partial class LocalMediaStorage(IConfiguration configuration) : IMediaStorage
{
    private static readonly Dictionary<string, string> ContentTypes = new(StringComparer.OrdinalIgnoreCase)
    {
        [".mp4"] = "video/mp4",
        [".m4v"] = "video/mp4",
        [".mov"] = "video/quicktime",
        [".webm"] = "video/webm",
        [".glb"] = "model/gltf-binary",
        [".fbx"] = "application/octet-stream",
        [".jpg"] = "image/jpeg",
        [".png"] = "image/png",
    };

    private readonly string _root = Path.GetFullPath(configuration["Media:LocalPath"] ?? Path.Combine(Path.GetTempPath(), "myhealth-media"));

    private readonly string _publicBaseUrl = (configuration["Media:PublicBaseUrl"] ?? "https://media.myhealth.app").TrimEnd('/');

    public async Task SaveAsync(string key, Stream content, string contentType, CancellationToken cancellationToken)
    {
        var path = PathOf(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var temporary = path + ".uploading";
        await using (var file = File.Create(temporary))
        {
            await content.CopyToAsync(file, cancellationToken);
        }

        File.Move(temporary, path, overwrite: true);
    }

    public Task<StoredMedia?> OpenAsync(string key, CancellationToken cancellationToken)
    {
        // Keys can come from a URL here: an invalid one is simply not found.
        if (!IsSafe(key))
        {
            return Task.FromResult<StoredMedia?>(null);
        }

        var path = PathOf(key);
        if (!File.Exists(path))
        {
            return Task.FromResult<StoredMedia?>(null);
        }

        var stream = File.OpenRead(path);
        var type = ContentTypes.GetValueOrDefault(Path.GetExtension(path), "application/octet-stream");
        return Task.FromResult<StoredMedia?>(new StoredMedia(stream, type, stream.Length));
    }

    public Task DeleteAsync(string key, CancellationToken cancellationToken)
    {
        var path = PathOf(key);
        if (File.Exists(path))
        {
            File.Delete(path);
        }

        return Task.CompletedTask;
    }

    public string PublicUrl(string key) =>
        key.StartsWith(IMediaStorage.PublicPrefix, StringComparison.Ordinal)
            ? $"{_publicBaseUrl}/{key[IMediaStorage.PublicPrefix.Length..]}"
            : throw new InvalidOperationException("Only public media has a URL.");

    /// <summary>Keys are generated by MyHealth, but are still checked so no key can leave the storage folder.</summary>
    private string PathOf(string key)
    {
        if (!IsSafe(key))
        {
            throw new ArgumentException("Invalid media key.", nameof(key));
        }

        return Path.Combine(_root, key.Replace('/', Path.DirectorySeparatorChar));
    }

    private static bool IsSafe(string key) => SafeKey().IsMatch(key) && !key.Contains("..", StringComparison.Ordinal);

    [GeneratedRegex("^[a-z0-9][a-z0-9/_.-]{0,300}$")]
    private static partial Regex SafeKey();
}
