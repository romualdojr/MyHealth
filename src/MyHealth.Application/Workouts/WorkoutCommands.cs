public sealed record StartWorkoutResponse(Guid SessionId, Guid PlanVersionId, int PlanVersionNumber, bool Created);

/// <summary>
/// Starts a session of the plan's current version. <paramref name="SessionId"/> is generated by the phone; repeating the
/// call with the same id is a no-op (it is also the HealthKit workout id).
/// </summary>
public sealed record StartWorkoutCommand(Guid SessionId, Guid PlanId, Guid PlannedSessionId, DateTimeOffset StartedAt, string? TimeZoneId)
    : ICommand<StartWorkoutResponse>;

internal sealed class StartWorkoutValidator : AbstractValidator<StartWorkoutCommand>
{
    public StartWorkoutValidator()
    {
        RuleFor(c => c.SessionId).NotEmpty();
        RuleFor(c => c.PlanId).NotEmpty();
        RuleFor(c => c.PlannedSessionId).NotEmpty();
        RuleFor(c => c.TimeZoneId).Must(TimeZones.IsValid).When(c => c.TimeZoneId is not null).WithMessage("Unknown time zone.");
    }
}

internal sealed class StartWorkoutHandler(
    IUserContext user, IUserProfileRepository users, ITrainingPlanRepository plans, ITrainingPlanVersionRepository versions,
    IWorkoutSessionRepository sessions, IUnitOfWork unitOfWork, TimeProvider clock)
    : ICommandHandler<StartWorkoutCommand, StartWorkoutResponse>
{
    public async Task<Result<StartWorkoutResponse>> Handle(StartWorkoutCommand command, CancellationToken cancellationToken)
    {
        var existing = await sessions.GetByIdAsync(command.SessionId, cancellationToken);
        if (existing is not null)
        {
            return existing.IsSameStart(user.UserId, command.PlanId, command.PlannedSessionId)
                ? new StartWorkoutResponse(existing.Id, existing.PlanVersionId, existing.PlanVersionNumber, Created: false)
                : WorkoutErrors.IdConflict;
        }

        var profile = await users.GetByIdAsync(user.UserId, cancellationToken);
        if (profile is null)
        {
            return UserErrors.ProfileNotFound;
        }

        var plan = await plans.GetByIdAsync(command.PlanId, cancellationToken);
        if (plan is null || plan.ClientId != user.UserId)
        {
            return PlanErrors.NotFound;
        }

        if (plan.Status != PlanStatus.Published || plan.CurrentVersionId is not { } versionId)
        {
            return PlanErrors.NotPublished;
        }

        var version = await versions.GetByIdAsync(versionId, cancellationToken);
        if (version is null)
        {
            return PlanErrors.VersionNotFound;
        }

        var session = WorkoutSession.Start(
            command.SessionId, user.UserId, version, command.PlannedSessionId, command.StartedAt,
            command.TimeZoneId ?? profile.TimeZoneId, clock.GetUtcNow());
        if (session.IsFailure)
        {
            return session.Error;
        }

        sessions.Add(session.Value);
        await unitOfWork.SaveChangesAsync(cancellationToken);
        return new StartWorkoutResponse(session.Value.Id, version.Id, version.VersionNumber, Created: true);
    }
}

public enum WorkoutTransition
{
    Pause = 1,
    Resume = 2,
    Abandon = 3,
}

public sealed record ChangeWorkoutStateCommand(Guid SessionId, WorkoutTransition Transition, DateTimeOffset At) : ICommand;

internal sealed class ChangeWorkoutStateValidator : AbstractValidator<ChangeWorkoutStateCommand>
{
    public ChangeWorkoutStateValidator() => RuleFor(c => c.Transition).IsInEnum();
}

internal sealed class ChangeWorkoutStateHandler(IUserContext user, IWorkoutSessionRepository sessions, IUnitOfWork unitOfWork)
    : ICommandHandler<ChangeWorkoutStateCommand>
{
    public async Task<Result> Handle(ChangeWorkoutStateCommand command, CancellationToken cancellationToken)
    {
        var session = await sessions.GetByIdAsync(command.SessionId, cancellationToken);
        if (session is null || session.ClientId != user.UserId)
        {
            return WorkoutErrors.NotFound;
        }

        var result = command.Transition switch
        {
            WorkoutTransition.Pause => session.Pause(command.At),
            WorkoutTransition.Resume => session.Resume(command.At),
            _ => session.Abandon(command.At),
        };

        if (result.IsSuccess)
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }

        return result;
    }
}

/// <summary>Records (or corrects, with the same <paramref name="SetLogId"/>) one performed set.</summary>
public sealed record LogSetCommand(
    Guid SessionId,
    Guid SetLogId,
    Guid ExerciseId,
    Guid? PlannedExerciseId,
    int SetNumber,
    int? Repetitions,
    decimal? LoadKg,
    int? DurationSeconds,
    decimal? DistanceMeters,
    int? Difficulty,
    string? Notes,
    DateTimeOffset LoggedAt) : ICommand;

internal sealed class LogSetValidator : AbstractValidator<LogSetCommand>
{
    public LogSetValidator()
    {
        RuleFor(c => c.SetLogId).NotEmpty();
        RuleFor(c => c.ExerciseId).NotEmpty();
        RuleFor(c => c.SetNumber).InclusiveBetween(1, 100);
        RuleFor(c => c.Repetitions).InclusiveBetween(0, 1000);
        RuleFor(c => c.LoadKg).InclusiveBetween(0, 1000);
        RuleFor(c => c.DurationSeconds).InclusiveBetween(0, 86_400);
        RuleFor(c => c.DistanceMeters).InclusiveBetween(0, 1_000_000);
        RuleFor(c => c.Difficulty).InclusiveBetween(1, 10);
        RuleFor(c => c.Notes).MaximumLength(1000);
    }
}

internal sealed class LogSetHandler(IUserContext user, IWorkoutSessionRepository sessions, IUnitOfWork unitOfWork, TimeProvider clock)
    : ICommandHandler<LogSetCommand>
{
    public async Task<Result> Handle(LogSetCommand command, CancellationToken cancellationToken)
    {
        var session = await sessions.GetByIdAsync(command.SessionId, cancellationToken);
        if (session is null || session.ClientId != user.UserId)
        {
            return WorkoutErrors.NotFound;
        }

        var result = session.LogSet(
            new SetLogEntry(
                command.SetLogId, command.ExerciseId, command.PlannedExerciseId, command.SetNumber, command.Repetitions, command.LoadKg,
                command.DurationSeconds, command.DistanceMeters, command.Difficulty, command.Notes, command.LoggedAt),
            clock.GetUtcNow());

        if (result.IsSuccess)
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }

        return result;
    }
}

public sealed record CompleteWorkoutCommand(
    Guid SessionId,
    DateTimeOffset CompletedAt,
    int PerceivedExertion,
    bool ReportedDiscomfort,
    string? DiscomfortDetails,
    string? Comments) : ICommand;

internal sealed class CompleteWorkoutValidator : AbstractValidator<CompleteWorkoutCommand>
{
    public CompleteWorkoutValidator()
    {
        RuleFor(c => c.PerceivedExertion).InclusiveBetween(1, 10);
        RuleFor(c => c.DiscomfortDetails).MaximumLength(2000);
        RuleFor(c => c.Comments).MaximumLength(2000);
    }
}

internal sealed class CompleteWorkoutHandler(IUserContext user, IWorkoutSessionRepository sessions, IUnitOfWork unitOfWork, TimeProvider clock)
    : ICommandHandler<CompleteWorkoutCommand>
{
    public async Task<Result> Handle(CompleteWorkoutCommand command, CancellationToken cancellationToken)
    {
        var session = await sessions.GetByIdAsync(command.SessionId, cancellationToken);
        if (session is null || session.ClientId != user.UserId)
        {
            return WorkoutErrors.NotFound;
        }

        var feedback = new WorkoutFeedback(command.PerceivedExertion, command.ReportedDiscomfort, command.DiscomfortDetails, command.Comments);
        var result = session.Complete(feedback, command.CompletedAt, clock.GetUtcNow());
        if (result.IsSuccess)
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }

        return result;
    }
}

public sealed record ReplyToFeedbackCommand(Guid SessionId, string Message) : ICommand;

internal sealed class ReplyToFeedbackValidator : AbstractValidator<ReplyToFeedbackCommand>
{
    public ReplyToFeedbackValidator() => RuleFor(c => c.Message).NotEmpty().MaximumLength(2000);
}

internal sealed class ReplyToFeedbackHandler(
    ICareAccess access, IWorkoutSessionRepository sessions, IAuditLog audit, IUnitOfWork unitOfWork, TimeProvider clock)
    : ICommandHandler<ReplyToFeedbackCommand>
{
    public async Task<Result> Handle(ReplyToFeedbackCommand command, CancellationToken cancellationToken)
    {
        var trainer = await access.GetCurrentProfessionalAsync(Discipline.PersonalTrainer, requireVerified: true, cancellationToken);
        if (trainer.IsFailure)
        {
            return trainer.Error;
        }

        var session = await sessions.GetByIdAsync(command.SessionId, cancellationToken);
        if (session is null || session.TrainerProfileId != trainer.Value.Profile.Id || session.TenantId != trainer.Value.TenantId)
        {
            if (session is not null)
            {
                await audit.RecordDeniedAsync(nameof(WorkoutSession), session.Id, trainer.Value.TenantId, cancellationToken);
            }

            return WorkoutErrors.NotFound;
        }

        var relationship = await access.GetActiveRelationshipAsync(trainer.Value, session.ClientId, cancellationToken);
        if (relationship.IsFailure)
        {
            return relationship.Error;
        }

        var result = session.ReplyToFeedback(trainer.Value.Profile.Id, command.Message, clock.GetUtcNow());
        if (result.IsSuccess)
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }

        return result;
    }
}
