using MyHealth.Domain.Abstractions;
using MyHealth.Domain.Professionals;
using MyHealth.Domain.Users;

namespace MyHealth.Domain.Nutrition;

/// <summary>
/// How the meal relates to the plan. Worded neutrally on purpose (RF-30): eating something else or something unplanned is
/// information for the dietitian, not a failure.
/// </summary>
public enum MealAdherence
{
    AsPlanned = 1,
    Partly = 2,
    Different = 3,
    Unplanned = 4,
}

/// <summary>
/// Who the entry is for: a dietitian in one tenant, optionally against a meal of their plan. Entries without an addressee
/// stay private to the client. Set once, from the server's own records, never from a client-supplied tenant id.
/// </summary>
public sealed record DiaryAddressee(Guid TenantId, Guid DietitianProfileId, Guid? MealPlanId, int? MealPlanVersionNumber, Guid? PlannedMealId);

public sealed record FoodDiaryDetails(
    string? MealName,
    DateTimeOffset EatenAt,
    string TimeZoneId,
    string? Description,
    int? WaterMl,
    MealAdherence? Adherence,
    string? ClientNotes);

public sealed class FoodDiaryComment : Entity<Guid>
{
    internal FoodDiaryComment(Guid id, ProfessionalProfile author, string message, DateTimeOffset createdAt) : base(id)
    {
        AuthorProfileId = author.Id;
        AuthorUserId = author.UserId;
        Message = message;
        CreatedAt = createdAt;
    }

    private FoodDiaryComment() { }

    public Guid AuthorProfileId { get; private set; }

    public Guid AuthorUserId { get; private set; }

    public string Message { get; private set; } = null!;

    public DateTimeOffset CreatedAt { get; private set; }
}

/// <summary>
/// One meal or glass of water logged by the client (RF-30). The id is generated by the phone, so saving is an
/// idempotent upsert that works offline (RNF-09). Never visible to trainers.
/// </summary>
public sealed class FoodDiaryEntry : AggregateRoot<Guid>
{
    private readonly List<FoodDiaryComment> _comments = [];

    private FoodDiaryEntry(Guid id) : base(id) { }

    private FoodDiaryEntry() { }

    public Guid ClientId { get; private set; }

    /// <summary>The tenant of the dietitian the entry is for, or <c>null</c> for a private entry.</summary>
    public Guid? TenantId { get; private set; }

    public Guid? DietitianProfileId { get; private set; }

    public Guid? MealPlanId { get; private set; }

    public int? MealPlanVersionNumber { get; private set; }

    public Guid? PlannedMealId { get; private set; }

    public string? MealName { get; private set; }

    public DateTimeOffset EatenAt { get; private set; }

    public string TimeZoneId { get; private set; } = null!;

    /// <summary>The client's local date of the meal, used to group the diary by day.</summary>
    public DateOnly LocalDate { get; private set; }

    public string? Description { get; private set; }

    public int? WaterMl { get; private set; }

    public MealAdherence? Adherence { get; private set; }

    /// <summary>Difficulties or feelings the client wants the dietitian to know.</summary>
    public string? ClientNotes { get; private set; }

    public DateTimeOffset RecordedAt { get; private set; }

    public DateTimeOffset UpdatedAt { get; private set; }

    public IReadOnlyCollection<FoodDiaryComment> Comments => _comments.AsReadOnly();

    public static Result<FoodDiaryEntry> Record(Guid id, Guid clientId, DiaryAddressee? addressee, FoodDiaryDetails details, DateTimeOffset now)
    {
        if (id == Guid.Empty)
        {
            return FoodDiaryErrors.InvalidId;
        }

        var entry = new FoodDiaryEntry(id)
        {
            ClientId = clientId,
            TenantId = addressee?.TenantId,
            DietitianProfileId = addressee?.DietitianProfileId,
            MealPlanId = addressee?.MealPlanId,
            MealPlanVersionNumber = addressee?.MealPlanVersionNumber,
            PlannedMealId = addressee?.PlannedMealId,
            RecordedAt = now,
        };

        var applied = entry.Apply(details, now);
        if (applied.IsSuccess && addressee is not null && !string.IsNullOrWhiteSpace(entry.ClientNotes))
        {
            entry.Raise(new FoodDiaryNoteShared(entry.Id, addressee.TenantId, clientId, addressee.DietitianProfileId, now));
        }

        return applied.IsFailure ? applied.Error : entry;
    }

    /// <summary>True when a retried save names the same plan and meal, so it may update this entry.</summary>
    public bool HasSameAddressee(Guid clientId, DiaryAddressee? addressee) =>
        ClientId == clientId
        && TenantId == addressee?.TenantId
        && DietitianProfileId == addressee?.DietitianProfileId
        && MealPlanId == addressee?.MealPlanId
        && PlannedMealId == addressee?.PlannedMealId;

    /// <summary>The client corrects their own entry. The dietitian's comments stay.</summary>
    public Result Revise(Guid clientId, FoodDiaryDetails details, DateTimeOffset now) =>
        clientId != ClientId ? FoodDiaryErrors.NotFound : Apply(details, now);

    public Result Comment(ProfessionalProfile dietitian, string message, DateTimeOffset now)
    {
        if (DietitianProfileId != dietitian.Id)
        {
            return FoodDiaryErrors.NotAddressee;
        }

        if (string.IsNullOrWhiteSpace(message))
        {
            return FoodDiaryErrors.EmptyComment;
        }

        var comment = new FoodDiaryComment(Guid.CreateVersion7(now), dietitian, message.Trim(), now);
        _comments.Add(comment);
        Raise(new FoodDiaryCommented(Id, TenantId!.Value, ClientId, comment.Id, now));
        return Result.Success();
    }

    private Result Apply(FoodDiaryDetails details, DateTimeOffset now)
    {
        if (string.IsNullOrWhiteSpace(details.Description) && details.WaterMl is null && PlannedMealId is null)
        {
            return FoodDiaryErrors.Empty;
        }

        if (details.WaterMl is < 1 or > 10_000)
        {
            return FoodDiaryErrors.InvalidWater;
        }

        if (details.EatenAt > now + Training.Workouts.WorkoutSession.ClockSkewTolerance)
        {
            return FoodDiaryErrors.FutureTimestamp;
        }

        if (!TimeZones.IsValid(details.TimeZoneId))
        {
            return UserErrors.InvalidTimeZone;
        }

        MealName = details.MealName?.Trim();
        EatenAt = details.EatenAt;
        TimeZoneId = details.TimeZoneId;
        LocalDate = TimeZones.LocalDate(details.EatenAt, details.TimeZoneId);
        Description = details.Description?.Trim();
        WaterMl = details.WaterMl;
        Adherence = details.Adherence;
        ClientNotes = details.ClientNotes?.Trim();
        UpdatedAt = now;
        return Result.Success();
    }
}

public sealed record FoodDiaryCommented(Guid EntryId, Guid TenantId, Guid ClientId, Guid CommentId, DateTimeOffset OccurredAt) : DomainEvent(OccurredAt);

/// <summary>A new entry shared with a dietitian carries a note from the client: the dietitian is told, like workout feedback.</summary>
public sealed record FoodDiaryNoteShared(Guid EntryId, Guid TenantId, Guid ClientId, Guid DietitianProfileId, DateTimeOffset OccurredAt) : DomainEvent(OccurredAt);

public interface IFoodDiaryRepository : IRepository<FoodDiaryEntry, Guid>;

public static class FoodDiaryErrors
{
    public static readonly Error NotFound = Error.NotFound("FoodDiary.NotFound", "The diary entry was not found.");
    public static readonly Error InvalidId = Error.Validation("FoodDiary.InvalidId", "A client-generated entry id is required.");
    public static readonly Error IdConflict = Error.Conflict("FoodDiary.IdConflict", "This entry id is already used for a different plan or meal.");
    public static readonly Error Empty = Error.Validation("FoodDiary.Empty", "Describe the meal, pick a planned meal, or record water.");
    public static readonly Error InvalidWater = Error.Validation("FoodDiary.InvalidWater", "Water must be between 1 and 10,000 ml.");
    public static readonly Error FutureTimestamp = Error.Validation("FoodDiary.FutureTimestamp", "The meal time is in the future.");
    public static readonly Error EmptyComment = Error.Validation("FoodDiary.EmptyComment", "The comment is empty.");
    public static readonly Error NotAddressee = Error.Forbidden("FoodDiary.NotAddressee", "Only the dietitian this entry was shared with can comment.");
    public static readonly Error PlannedMealNotFound = Error.Validation("FoodDiary.PlannedMealNotFound", "The meal is not part of the current plan version.");
    public static readonly Error NoDietitianRelationship = Error.Validation(
        "FoodDiary.NoDietitianRelationship", "The diary can only be shared with a dietitian you have an active relationship with.");
}
